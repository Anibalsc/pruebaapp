-- ============================================================
-- Integra precios web con el radar geolocalizado existente.
-- Se conserva la firma y el resultado de la función actual.
-- ============================================================

create or replace function public.joseo_prices_nearby(
  p_lat double precision,
  p_lng double precision,
  p_radius_km double precision default 20
)
returns table (
  record_key text,
  source_kind text,
  community_price_id bigint,
  official_price_id bigint,
  user_id text,
  product_id bigint,
  product text,
  branch_id bigint,
  branch text,
  store_id bigint,
  supermarket text,
  price double precision,
  regular_price double precision,
  is_offer boolean,
  observed_at text,
  source_period text,
  source_type text,
  source_quality text,
  source_url text,
  source_document text,
  note text,
  photo_url text,
  confirmed_count integer,
  incorrect_count integer,
  verified_place boolean,
  can_vote boolean,
  xp_eligible boolean,
  radar_candidate boolean,
  distance_km double precision,
  is_best_nearby boolean
)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  with validated_input as (
    select
      case when p_lat between -90 and 90 then p_lat else null end as latitude,
      case when p_lng between -180 and 180 then p_lng else null end as longitude,
      least(greatest(coalesce(p_radius_km, 20), 1), 50) as radius_km
  ),
  branch_candidates as (
    select
      b.id::bigint as branch_id,
      (
        6371 * acos(
          least(1.0, greatest(-1.0,
            cos(radians(i.latitude)) * cos(radians(b.latitude))
            * cos(radians(b.longitude) - radians(i.longitude))
            + sin(radians(i.latitude)) * sin(radians(b.latitude))
          ))
        )
      )::double precision as distance_km,
      i.radius_km
    from public.branches b
    join public.stores s on s.id = b.store_id
    cross join validated_input i
    where i.latitude is not null
      and i.longitude is not null
      and b.latitude is not null
      and b.longitude is not null
      and b.active = true
      and s.active = true
      and b.verification_status = 'verified'
      and s.verification_status = 'verified'
  ),
  nearby_branches as (
    select branch_id, distance_km
    from branch_candidates
    where distance_km <= radius_km
  ),
  all_prices as (
    -- Fuente comunitaria/oficial que JOSEO ya tiene funcionando.
    select
      ap.record_key::text as record_key,
      ap.source_kind::text as source_kind,
      ap.community_price_id::bigint as community_price_id,
      ap.official_price_id::bigint as official_price_id,
      ap.user_id::text as user_id,
      ap.product_id::bigint as product_id,
      ap.product::text as product,
      ap.branch_id::bigint as branch_id,
      ap.branch::text as branch,
      ap.store_id::bigint as store_id,
      ap.supermarket::text as supermarket,
      ap.price::double precision as price,
      ap.regular_price::double precision as regular_price,
      coalesce(ap.is_offer, false)::boolean as is_offer,
      ap.observed_at::timestamptz as observed_at,
      coalesce(ap.source_period, '')::text as source_period,
      coalesce(ap.source_type, '')::text as source_type,
      coalesce(ap.source_quality, '')::text as source_quality,
      coalesce(ap.source_url, '')::text as source_url,
      coalesce(ap.source_document, '')::text as source_document,
      coalesce(ap.note, '')::text as note,
      ap.photo_url::text as photo_url,
      coalesce(ap.confirmed_count, 0)::integer as confirmed_count,
      coalesce(ap.incorrect_count, 0)::integer as incorrect_count,
      coalesce(ap.verified_place, false)::boolean as verified_place,
      coalesce(ap.can_vote, false)::boolean as can_vote,
      coalesce(ap.xp_eligible, false)::boolean as xp_eligible,
      coalesce(ap.radar_candidate, false)::boolean as radar_candidate
    from public.joseo_all_prices ap

    union all

    -- Fuente web: solo productos emparejados con products y observaciones actuales.
    select
      ('web:' || w.id)::text as record_key,
      'official'::text as source_kind,
      null::bigint as community_price_id,
      w.id::bigint as official_price_id,
      ''::text as user_id,
      w.product_id::bigint,
      coalesce(p.name, w.product_name)::text as product,
      w.branch_id::bigint,
      b.name::text as branch,
      w.store_id::bigint,
      s.name::text as supermarket,
      w.price::double precision,
      w.regular_price::double precision,
      w.is_offer::boolean,
      w.observed_at::timestamptz,
      'web'::text as source_period,
      w.source_type::text,
      'official-site'::text as source_quality,
      w.source_url::text,
      ''::text as source_document,
      coalesce(w.note, '')::text,
      null::text as photo_url,
      0::integer as confirmed_count,
      0::integer as incorrect_count,
      true::boolean as verified_place,
      false::boolean as can_vote,
      false::boolean as xp_eligible,
      w.is_offer::boolean as radar_candidate
    from public.web_price_observations w
    join public.products p on p.id = w.product_id and p.active = true
    join public.branches b on b.id = w.branch_id
    join public.stores s on s.id = w.store_id
    where w.import_status = 'imported'
      and w.verification_status = 'verified'
      and w.available = true
      and w.price > 0
  ),
  eligible_prices as (
    select
      ap.*,
      nb.distance_km,
      row_number() over (
        partition by ap.product_id, ap.branch_id
        order by ap.observed_at desc nulls last, ap.record_key desc
      ) as freshness_rank
    from all_prices ap
    join nearby_branches nb on nb.branch_id = ap.branch_id
    where ap.verified_place = true
      and ap.price is not null
      and ap.price > 0
  ),
  latest_branch_prices as (
    select *
    from eligible_prices
    where freshness_rank = 1
  ),
  ranked_prices as (
    select
      lp.*,
      dense_rank() over (
        partition by lp.product_id
        order by lp.price asc
      ) as nearby_price_rank
    from latest_branch_prices lp
  )
  select
    rp.record_key::text,
    rp.source_kind::text,
    rp.community_price_id::bigint,
    rp.official_price_id::bigint,
    rp.user_id::text,
    rp.product_id::bigint,
    rp.product::text,
    rp.branch_id::bigint,
    rp.branch::text,
    rp.store_id::bigint,
    rp.supermarket::text,
    rp.price::double precision,
    rp.regular_price::double precision,
    coalesce(rp.is_offer, false)::boolean,
    rp.observed_at::text,
    coalesce(rp.source_period, '')::text,
    coalesce(rp.source_type, '')::text,
    coalesce(rp.source_quality, '')::text,
    coalesce(rp.source_url, '')::text,
    coalesce(rp.source_document, '')::text,
    coalesce(rp.note, '')::text,
    rp.photo_url::text,
    coalesce(rp.confirmed_count, 0)::integer,
    coalesce(rp.incorrect_count, 0)::integer,
    coalesce(rp.verified_place, false)::boolean,
    coalesce(rp.can_vote, false)::boolean,
    coalesce(rp.xp_eligible, false)::boolean,
    coalesce(rp.radar_candidate, false)::boolean,
    round(rp.distance_km::numeric, 2)::double precision,
    (rp.nearby_price_rank = 1)::boolean
  from ranked_prices rp
  order by lower(rp.product), rp.price asc, rp.distance_km asc;
$$;

revoke all on function public.joseo_prices_nearby(
  double precision, double precision, double precision
) from public;

grant execute on function public.joseo_prices_nearby(
  double precision, double precision, double precision
) to anon, authenticated;

commit;

