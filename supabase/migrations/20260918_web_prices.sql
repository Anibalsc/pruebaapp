-- JOSEO - PRECIOS WEB AUTOMÁTICOS (AISLADOS)
--
-- No modifica ni borra prices, joseo_community_prices ni branches.
-- Los precios web se guardan en tablas separadas y se agregan a
-- joseo_prices_nearby como una segunda fuente.
