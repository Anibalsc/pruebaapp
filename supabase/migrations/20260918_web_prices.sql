begin;

create table if not exists public.web_price_sources (
  id bigint generated by default as identity primary key,
  name text not null,
  base_url text not null,
  parser_type text not null default 'vtex',
  store_id bigint references public.stores(id) on delete cascade,
  branch_id bigint references public.branches(id) on delete cascade,
  enabled boolean not null default false,
  last_started_at timestamptz,
  last_success_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint web_price_sources_parser_check
    check (parser_type in ('vtex', 'jsonld')),
  constraint web_price_sources_url_check
    check (base_url ~ '^https?://')
);

create unique index if not exists web_price_sources_branch_url_idx
  on public.web_price_sources (coalesce(branch_id, 0), lower(base_url));

create table if not exists public.web_price_observations (
  id bigint generated by default as identity primary key,
  source_id bigint not null references public.web_price_sources(id) on delete cascade,
  store_id bigint not null references public.stores(id) on delete cascade,
  branch_id bigint not null references public.branches(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  external_product_id text not null,
  product_name text not null,
  brand text,
  size_text text,
  price numeric(12,2) not null check (price > 0),
  regular_price numeric(12,2) check (regular_price is null or regular_price > 0),
  currency text not null default 'DOP',
  is_offer boolean not null default false,
  available boolean not null default true,
  observed_at timestamptz not null default now(),
  observed_date date not null default current_date,
  source_url text not null,
  source_type text not null default 'official_web',
  verification_status text not null default 'verified',
  import_status text not null default 'imported',
  note text,
  raw jsonb,
  created_at timestamptz not null default now(),
  constraint web_price_observations_currency_check
    check (currency in ('DOP', 'USD')),
  constraint web_price_observations_status_check
    check (import_status in ('imported', 'unmatched', 'rejected', 'error')),
  constraint web_price_observations_verification_check
    check (verification_status in ('verified', 'pending', 'rejected')),
  constraint web_price_observations_daily_unique
    unique (source_id, external_product_id, observed_date)
);

create index if not exists web_price_observations_latest_idx
  on public.web_price_observations (branch_id, product_id, observed_at desc);

create index if not exists web_price_observations_status_idx
  on public.web_price_observations (import_status, verification_status, observed_at desc);

alter table public.web_price_sources enable row level security;
alter table public.web_price_observations enable row level security;

drop policy if exists joseo_web_prices_public_read on public.web_price_observations;
create policy joseo_web_prices_public_read
  on public.web_price_observations
  for select
  to anon, authenticated
  using (
    import_status = 'imported'
    and verification_status = 'verified'
    and available = true
  );

revoke all on public.web_price_sources from anon, authenticated;
revoke all on public.web_price_observations from anon, authenticated;
grant select on public.web_price_observations to anon, authenticated;

